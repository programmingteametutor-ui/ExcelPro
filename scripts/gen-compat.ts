// Generates docs/COMPATIBILITY.md from the live engine registry.
import fs from 'node:fs'
import path from 'node:path'
import { compatibilityMatrix, engineFunctions } from '../src/engine/compat'

const rows = compatibilityMatrix()
const counts = { supported: 0, partial: 0, unsupported: 0 }
for (const r of rows) counts[r.status]++
const icon = { supported: '✅ Supported', partial: '⚠️ Partial', unsupported: '❌ Unsupported' }

let md = `# Formula compatibility\n\nGenerated by \`npm run compat\` from the functions registered in the formula engine (HyperFormula ${'3.x'} + ExcelPro plugin). Do not edit by hand.\n\n`
md += `Of the ${rows.length} functions listed in the product spec: **${counts.supported} supported, ${counts.partial} partial, ${counts.unsupported} unsupported.** `
md += `The engine registers ${engineFunctions().size} functions in total.\n\n`
md += `Unsupported functions are never silently replaced: the formula text is kept, the cell shows \`#NAME?\`, and the status bar explains which function is missing. Imported workbooks list them in the import report.\n\n`
let cat = ''
for (const r of rows) {
  if (r.category !== cat) {
    cat = r.category
    md += `\n## ${cat}\n\n| Function | Status | Notes |\n|---|---|---|\n`
  }
  md += `| ${r.name} | ${icon[r.status]} | ${(r.note ?? '').replace(/\|/g, '\\|')} |\n`
}
md += `\n## Engine-wide differences from Excel\n\n`
md += `- Circular references evaluate to \`#CYCLE!\` (Excel shows 0 and a warning). Iterative calculation is not supported.\n`
md += `- \`#NULL!\` (intersection operator) is not produced; the space intersection operator is not supported.\n`
md += `- Dates use Excel's 1900 date system including the 1900 leap-year quirk; the 1904 system is not supported.\n`
md += `- Structured table references (Table1[Column]) and LAMBDA/LET are not supported.\n`
const out = path.resolve('docs/COMPATIBILITY.md')
fs.mkdirSync(path.dirname(out), { recursive: true })
fs.writeFileSync(out, md)
console.log(`wrote ${out}: ${JSON.stringify(counts)}`)
